"""Test vectors for the on-device self-test: raw features from unseen test days plus the int8 output the
Python TFLite interpreter gives. The ESP32 (or QEMU in CI) must reproduce them with TFLite Micro.

    python ml/export_vectors.py   -> firmware/main/test_vectors.h
"""
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "..", "week-3", "tinyml"))
from occupancy import FEATURES, TRAIN_DAYS, make_features  # noqa: E402
from tflite_utils import TFLiteModel  # noqa: E402

N = 96


def main():
    df = pd.read_csv(os.path.join(ROOT, "data", "home_1min.csv"), parse_dates=["timestamp"])
    X = make_features(df)[FEATURES].to_numpy(np.float32)
    day = (df.timestamp - df.timestamp.min()).dt.days.to_numpy()
    rng = np.random.default_rng(1)
    idx = rng.choice(np.where(day >= TRAIN_DAYS)[0], N, replace=False)
    mean, std = np.load(os.path.join(HERE, "norm.npy")).astype(np.float32)
    lite = TFLiteModel(os.path.join(HERE, "occupancy_int8.tflite"))
    s, z = lite.inp["quantization"]
    exp = []
    for i in idx:
        q = np.clip(np.round(((X[i] - mean) / std) / np.float32(s) + z), -128, 127).astype(np.int8)[None]
        lite.it.set_tensor(lite.inp["index"], q)
        lite.it.invoke()
        exp.append(int(lite.it.get_tensor(lite.out["index"])[0, 0]))
    rows = ",\n".join("  {" + ", ".join(f"{v:.6f}f" for v in X[i]) + "}" for i in idx)
    labels = df.occupied.to_numpy()[idx]
    open(os.path.join(ROOT, "firmware", "main", "test_vectors.h"), "w").write(f"""// Generated by ml/export_vectors.py: {N} rows from unseen test days.
#pragma once
#include <cstdint>
#include "model_data.h"
constexpr int kNumVectors = {N};
constexpr float kVectorFeatures[kNumVectors][kNumFeatures] = {{
{rows}
}};
// int8 output of the Python TFLite interpreter for each row
constexpr int8_t kVectorExpected[kNumVectors] = {{{", ".join(map(str, exp))}}};
// true occupancy label for each row
constexpr uint8_t kVectorLabel[kNumVectors] = {{{", ".join(map(str, labels))}}};
""")
    print(f"{N} vectors; label accuracy of the expected outputs: {np.mean((np.array(exp) > 0) == labels):.3f}")


if __name__ == "__main__":
    main()
