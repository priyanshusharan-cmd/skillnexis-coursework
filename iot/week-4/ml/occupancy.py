"""Occupancy prediction from cheap sensors (PIR, sound, temperature) plus time of day.

Features are computed causally: only the past, exactly as the ESP32 can compute them in a ring buffer.
Train on days 1-20, test on days 21-28 (whole unseen days, so weekday/weekend patterns can't leak).

Models compared: the usual "motion in the last 10 min" timer, logistic regression, random forest, and a
small MLP that is quantised to int8 for TensorFlow Lite Micro on the ESP32.

    python ml/occupancy.py  -> ml/occupancy_int8.tflite, firmware/main/model_data.{h,cc}, results/occupancy.md
"""
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
FEATURES = ["motion_1", "motion_5", "motion_15", "motion_30", "since_motion", "sound_mean5", "sound_max5",
            "sound_std15", "temp_delta30", "hour_sin", "hour_cos", "weekend", "bedroom"]
TRAIN_DAYS = 20


def make_features(df):
    out = []
    for room, g in df.groupby("room", sort=False):
        g = g.sort_values("timestamp").copy()
        m = g.motion
        f = pd.DataFrame(index=g.index)
        f["motion_1"] = m
        for w in (5, 15, 30):
            f[f"motion_{w}"] = m.rolling(w, 1).sum()
        last = g.timestamp.where(m == 1).ffill()
        f["since_motion"] = ((g.timestamp - last).dt.total_seconds() / 60).fillna(120).clip(0, 120)
        f["sound_mean5"] = g.sound_db.rolling(5, 1).mean()
        f["sound_max5"] = g.sound_db.rolling(5, 1).max()
        f["sound_std15"] = g.sound_db.rolling(15, 2).std().fillna(0)
        f["temp_delta30"] = g.temp_c - g.temp_c.shift(30).bfill()
        h = g.timestamp.dt.hour + g.timestamp.dt.minute / 60
        f["hour_sin"], f["hour_cos"] = np.sin(2 * np.pi * h / 24), np.cos(2 * np.pi * h / 24)
        f["weekend"] = (g.timestamp.dt.dayofweek >= 5).astype(int)
        f["bedroom"] = int(room == "bedroom")
        out.append(f)
    return pd.concat(out).loc[df.index]


def scores(y, p, still):
    tp, fp = ((p == 1) & (y == 1)).sum(), ((p == 1) & (y == 0)).sum()
    fn = ((p == 0) & (y == 1)).sum()
    return {"acc": (p == y).mean(), "f1": 2 * tp / (2 * tp + fp + fn), "still_recall": p[still & (y == 1)].mean(),
            "false_occ": fp / max(1, (y == 0).sum())}


def export_c(blob, mean, std, path_h, path_cc):
    os.makedirs(os.path.dirname(path_h), exist_ok=True)
    arr = ",".join(f"0x{b:02x}" if i % 16 else f"\n  0x{b:02x}" for i, b in enumerate(blob))
    fl = lambda v: ", ".join(f"{x:.6f}f" for x in v)  # noqa: E731
    open(path_h, "w").write(f"""// Generated by ml/occupancy.py. Do not edit.
#pragma once
#include <cstdint>
constexpr int kNumFeatures = {len(mean)};
extern const unsigned char g_occupancy_model[];
extern const unsigned int g_occupancy_model_len;
// feature standardisation: x' = (x - mean) / std, order as in ml/occupancy.py FEATURES
constexpr float kFeatureMean[kNumFeatures] = {{{fl(mean)}}};
constexpr float kFeatureStd[kNumFeatures] = {{{fl(std)}}};
""")
    open(path_cc, "w").write(f"""// Generated by ml/occupancy.py: int8 TFLite flatbuffer ({len(blob)} bytes)
#include "model_data.h"
alignas(16) const unsigned char g_occupancy_model[] = {{{arr}
}};
const unsigned int g_occupancy_model_len = {len(blob)};
""")


def main():
    import tensorflow as tf
    from sklearn.ensemble import RandomForestClassifier
    from sklearn.linear_model import LogisticRegression
    sys.path.insert(0, os.path.join(ROOT, "..", "week-3", "tinyml"))
    from tflite_utils import TFLiteModel, to_int8_tflite

    tf.keras.utils.set_random_seed(0)
    df = pd.read_csv(os.path.join(ROOT, "data", "home_1min.csv"), parse_dates=["timestamp"])
    X = make_features(df)[FEATURES].to_numpy(np.float32)
    y = df.occupied.to_numpy()
    day = (df.timestamp - df.timestamp.min()).dt.days.to_numpy()
    tr, te = day < TRAIN_DAYS, day >= TRAIN_DAYS
    still = (df.awake.eq(1) & X[:, FEATURES.index("since_motion")].__gt__(10)) | df.asleep.eq(1)
    still = still.to_numpy()
    mean, std = X[tr].mean(0), X[tr].std(0) + 1e-6
    Z = (X - mean) / std

    res = {"Motion in last 10 min (PIR timer)": (X[te, FEATURES.index("since_motion")] < 10).astype(int)}
    lr = LogisticRegression(max_iter=1000).fit(Z[tr], y[tr])
    res["Logistic regression"] = lr.predict(Z[te])
    rf = RandomForestClassifier(200, min_samples_leaf=20, n_jobs=-1, random_state=0).fit(X[tr], y[tr])
    res["Random forest (200 trees)"] = rf.predict(X[te])

    model = tf.keras.Sequential([tf.keras.layers.Input((len(FEATURES),)),
                                 tf.keras.layers.Dense(24, activation="relu"),
                                 tf.keras.layers.Dense(12, activation="relu"),
                                 tf.keras.layers.Dense(1, activation="sigmoid")])
    model.compile(tf.keras.optimizers.Adam(2e-3), "binary_crossentropy", metrics=["accuracy"])
    model.fit(Z[tr], y[tr], epochs=30, batch_size=256, validation_split=0.1, verbose=0,
              callbacks=[tf.keras.callbacks.EarlyStopping(patience=4, restore_best_weights=True)])
    res["MLP float32"] = (model.predict(Z[te], verbose=0, batch_size=4096)[:, 0] > 0.5).astype(int)
    path = os.path.join(HERE, "occupancy_int8.tflite")
    size = to_int8_tflite(model, Z[tr][np.random.default_rng(0).permutation(tr.sum())], path)
    lite = TFLiteModel(path)
    p_int8 = np.array([lite.predict_proba(z)[0] for z in Z[te]])
    res["**MLP int8 (TFLite Micro, ESP32)**"] = (p_int8 > 0.5).astype(int)
    np.save(os.path.join(HERE, "test_proba_int8.npy"), p_int8)
    np.save(os.path.join(HERE, "norm.npy"), np.stack([mean, std]))
    export_c(open(path, "rb").read(), mean, std, os.path.join(ROOT, "firmware", "main", "model_data.h"),
             os.path.join(ROOT, "firmware", "main", "model_data.cc"))

    yt, st = y[te], still[te]
    lines = [f"Test: days {TRAIN_DAYS + 1}-28 ({te.sum():,} room-minutes, never seen in training). "
             f"\"Still\" = someone present but asleep or without motion for > 10 min ({(st & (yt == 1)).sum():,} minutes).", "",
             "| Model | Accuracy | F1 | Recall while people sit still | Empty room called occupied |", "|---|---:|---:|---:|---:|"]
    for name, p in res.items():
        s = scores(yt, p, st)
        lines.append(f"| {name} | {s['acc']:.3f} | {s['f1']:.3f} | {s['still_recall']:.2f} | {s['false_occ']:.1%} |")
    imp = sorted(zip(FEATURES, rf.feature_importances_), key=lambda t: -t[1])[:5]
    lines += ["", f"MLP: {model.count_params()} parameters, int8 flatbuffer **{size:,} bytes** (fits easily in ESP32 flash; "
              f"tensor arena 2 KB), {lite.latency_ms(Z[te][0]) * 1000:.0f} µs per inference on this PC.",
              "Most useful features (random forest): " + ", ".join(f"{k} {v:.2f}" for k, v in imp) + "."]
    os.makedirs(os.path.join(ROOT, "results"), exist_ok=True)
    open(os.path.join(ROOT, "results", "occupancy.md"), "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
